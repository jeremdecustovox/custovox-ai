"""Generate demo-engine.js (the /demo page analysis) from callscope-ai's lexicon.

The rules are a line-by-line port of callscope-ai (analysis.py: sentiment, contact reasons,
key moments) and custovox-calls (actions.py: suggested actions). The word lists are not
copied by hand: they are read from mcp/callscope-ai/src/callscope/lexicon.py, so the page
and the published package always use the same lists. tools/demo/test_demo_parity.py checks
that the JavaScript and the Python packages give the same result on fictional texts.

Usage: python tools/demo/build_demo_engine.py   (writes demo-engine.js at the site root)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "mcp" / "callscope-ai" / "src"))
from callscope import __version__, lexicon  # noqa: E402

LEX = {
    "version": __version__,
    "positive": sorted(lexicon.POSITIVE),
    "negative": sorted(lexicon.NEGATIVE),
    "negators": sorted(lexicon.NEGATORS),
    "reasons": lexicon.REASONS,
    "moments": lexicon.MOMENTS,
}

ENGINE = r"""/* custovox.ai demo engine — generated by tools/demo/build_demo_engine.py, do not edit by hand.
   Runs entirely in the visitor's browser: the pasted texts are never sent anywhere.
   Port of callscope-ai __VERSION__ (simple French/English keyword rules) and of the
   suggested-action rules of custovox-calls. MIT, CustoVox.ai. */
(function (root) {
  'use strict';
  var LEX = __LEX__;
  var POS = new Set(LEX.positive), NEG = new Set(LEX.negative), NOT = new Set(LEX.negators);
  var WORD = /[\p{L}\p{N}\p{M}_'’-]+/gu;
  var W = '[\\p{L}\\p{N}\\p{M}_]';
  var ESC = /[.*+?^${}()|[\]\\]/g;
  var hasCache = {};

  function words(text) { return (text.match(WORD) || []).map(function (w) { return w.toLowerCase(); }); }
  function score(text) {
    var ws = words(text), s = 0;
    ws.forEach(function (w, i) {
      var sign = POS.has(w) ? 1 : NEG.has(w) ? -1 : 0;
      if (sign && ws.slice(Math.max(0, i - 2), i).some(function (p) { return NOT.has(p); })) sign = -sign;
      s += sign;
    });
    return Math.max(-1, Math.min(1, s / 3));
  }
  function has(text, kw) {
    var re = hasCache[kw] || (hasCache[kw] = new RegExp('(?<!' + W + ')' + kw.replace(ESC, '\\$&') + '(?!' + W + ')', 'u'));
    return re.test(text);
  }
  function label(s) { return s > 0.15 ? 'positive' : s < -0.15 ? 'negative' : 'neutral'; }
  function round2(x) { return Math.round(x * 100) / 100; }

  function analyzeText(text) {
    var low = text.toLowerCase(), s = score(text);
    var reasons = [];
    Object.keys(LEX.reasons).forEach(function (r) {
      var hits = LEX.reasons[r].filter(function (k) { return has(low, k); });
      if (hits.length) reasons.push({ reason: r, matches: Array.from(new Set(hits)).sort(), score: new Set(hits).size });
    });
    reasons.sort(function (a, b) { return b.score - a.score || (a.reason < b.reason ? -1 : 1); });
    var moments = [];
    ['complaint', 'churn_threat'].forEach(function (kind) {   // customer moments only: every text is the customer's
      var hit = LEX.moments[kind].find(function (k) { return has(low, k); });
      if (hit) moments.push({ type: kind, match: hit });
    });
    return { score: round2(s), label: label(s), reasons: reasons, moments: moments };
  }

  var PRIO = { high: 0, medium: 1, low: 2 };
  function suggest(a) {   // custovox-calls actions.suggest, for one text
    var acts = [], mean = a.score, rs = a.reasons.map(function (r) { return r.reason; });
    a.moments.forEach(function (m) {
      if (m.type === 'churn_threat') acts.push({ type: 'manager_alert', priority: 'high', why: 'churn_threat' });
      else if (m.type === 'complaint') acts.push({ type: 'manager_alert', priority: 'medium', why: 'complaint' });
    });
    if (mean < -0.15 || a.moments.some(function (m) { return m.type === 'complaint'; }))
      acts.push({ type: 'crm_ticket', priority: mean < -0.4 ? 'high' : 'medium', why: 'negative', reasons: rs });
    var alerts = acts.filter(function (x) { return x.type === 'manager_alert'; })
      .sort(function (x, y) { return PRIO[x.priority] - PRIO[y.priority]; });
    acts = acts.filter(function (x) { return x.type !== 'manager_alert'; }).concat(alerts.slice(0, 1));
    return acts.sort(function (x, y) { return PRIO[x.priority] - PRIO[y.priority]; });
  }

  function report(texts) {
    var per = texts.map(function (t, i) { var a = analyzeText(t); a.index = i; a.text = t; return a; });
    var n = per.length, counts = { positive: 0, neutral: 0, negative: 0 }, byReason = {}, actions = [];
    per.forEach(function (a) {
      counts[a.label]++;
      a.reasons.forEach(function (r) { byReason[r.reason] = (byReason[r.reason] || 0) + 1; });
      var acts = suggest(a);
      a.actions = acts.map(function (x) { return { type: x.type, priority: x.priority }; });
      acts.forEach(function (x) { x.index = a.index; x.score = a.score; x.evidence = a.text; actions.push(x); });
    });
    var TYPE = { manager_alert: 0, crm_ticket: 1 };
    actions.sort(function (x, y) { return PRIO[x.priority] - PRIO[y.priority] || TYPE[x.type] - TYPE[y.type] || x.score - y.score || x.index - y.index; });
    var seen = new Set(), top = [];
    actions.forEach(function (x) { if (top.length < 3 && !seen.has(x.index)) { seen.add(x.index); top.push(x); } });
    return {
      engine: 'callscope-ai ' + LEX.version,
      count: n,
      mean: n ? round2(per.reduce(function (s, a) { return s + a.score; }, 0) / n) : 0,
      labels: counts,
      reasons: Object.keys(byReason).map(function (r) { return { reason: r, texts: byReason[r] }; })
        .sort(function (a, b) { return b.texts - a.texts || (a.reason < b.reason ? -1 : 1); }),
      churn: per.filter(function (a) { return a.moments.some(function (m) { return m.type === 'churn_threat'; }); })
        .map(function (a) { return { index: a.index, text: a.text }; }),
      complaints: per.filter(function (a) { return a.moments.some(function (m) { return m.type === 'complaint'; }); }).length,
      actions: top,
      per: per
    };
  }

  var api = { analyzeText: analyzeText, report: report, version: LEX.version };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.CustovoxDemo = api;
})(this);
"""


def main() -> None:
    js = ENGINE.replace("__LEX__", json.dumps(LEX, ensure_ascii=False)).replace("__VERSION__", __version__)
    out = ROOT / "demo-engine.js"
    out.write_text(js, encoding="utf-8")
    print(f"wrote {out.name} ({len(js.encode('utf-8'))} bytes, callscope-ai {__version__})")


if __name__ == "__main__":
    main()
