def nav_parts(lang: str, other_path: str) -> str:
    src = (ROOT / T[lang]["nav_source"]).read_text(encoding="utf-8")
    css = re.search(r'<style id="cvx-nav-css">.*?</style>', src, re.S).group(0)
    nav = re.search(r'<nav class="cvx-nav".*?</nav>', src, re.S).group(0)
    js = re.search(r'</nav>\s*(<script>.*?</script>)', src, re.S).group(1)
    nav = nav.replace('href="/merci.html"', f'href="{other_path}"').replace('href="/thank-you.html"', f'href="{other_path}"')
    return css, nav + "\n" + js


